import { appendFileSync, existsSync, readdirSync, readFileSync } from 'node:fs';
import { join } from 'node:path';
import { NskError } from '../errors.js';
import { execaRunner, notStarted, type Runner } from './exec.js';
import type { GeneratedFile } from './generate.js';

export interface ScaffoldOptions {
  /** Project name (package.json name is derived from it). */
  name: string;
  suiteApp: { publisherId: string; projectId: string } | null;
  /** Version of nsk itself, added as a devDependency so the npm scripts work without a global install. */
  nskVersion?: string;
}

/** Versions verified together with the generated rollup config (TS 7 checks, rollup + esbuild emit AMD). */
export const DEV_DEPENDENCIES = {
  '@hitc/netsuite-types': '^2026.2.4',
  esbuild: '^0.28.2',
  rollup: '^4.66.0',
  'rollup-plugin-esbuild': '^6.2.1',
  typescript: '^7.0.2',
};

const SOURCE_DIR = 'src/Source';

/** Folder `suitecloud project:create` creates: the project name, or <publisherid>.<projectid> for SuiteApps. */
export function projectFolderName(options: ScaffoldOptions): string {
  return options.suiteApp ? `${options.suiteApp.publisherId}.${options.suiteApp.projectId}` : options.name;
}

/** Folder that receives the AMD files: SuiteScripts, or the SuiteApp's own folder. */
export function scaffoldOutDir(options: ScaffoldOptions): string {
  return options.suiteApp
    ? `src/FileCabinet/SuiteApps/${options.suiteApp.publisherId}.${options.suiteApp.projectId}`
    : 'src/FileCabinet/SuiteScripts';
}

/** Files nsk adds on top of what `suitecloud project:create` generates. */
export function scaffoldFiles(dir: string, options: ScaffoldOptions): GeneratedFile[] {
  const outDir = scaffoldOutDir(options);
  return [
    { path: join(dir, 'package.json'), content: json(packageJson(options.name, options.nskVersion)) },
    { path: join(dir, 'tsconfig.json'), content: json(tsconfig(outDir)) },
    { path: join(dir, 'ns.config.json'), content: json({ bundler: 'rollup' }) },
    { path: join(dir, 'rollup.config.mjs'), content: rollupConfig(outDir) },
    { path: join(dir, SOURCE_DIR, '.gitkeep'), content: '' },
  ];
}

/** Refuses to scaffold into a folder that already has files, unless forced. */
export function assertEmptyFolder(dir: string, force: boolean): void {
  if (!force && existsSync(dir) && readdirSync(dir).length > 0) {
    throw new NskError(`${dir} already exists and is not empty.`, 'Pick another name or pass --force to overwrite.');
  }
}

/** Appends the entries missing from a .gitignore (creating it when needed). */
export function ensureGitignore(file: string, entries: string[]): void {
  const current = existsSync(file) ? readFileSync(file, 'utf8') : '';
  const lines = new Set(current.split(/\r?\n/).map((line) => line.trim()));
  const missing = entries.filter((entry) => !lines.has(entry));
  if (missing.length === 0) return;
  const separator = current === '' || current.endsWith('\n') ? '' : '\n';
  appendFileSync(file, `${separator}\n# nsk\n${missing.join('\n')}\n`);
}

export async function installDependencies(dir: string, runner: Runner = execaRunner): Promise<void> {
  const result = await runner('npm', ['install'], { cwd: dir, stdio: 'inherit' });
  if (notStarted(result)) {
    throw new NskError('npm not found.', 'Install Node.js/npm, then run "npm install" in the project.');
  }
  if (result.exitCode !== 0) {
    throw new NskError('npm install failed.', `Fix the error above and run "npm install" in ${dir}.`);
  }
}

function packageJson(name: string, nskVersion: string | undefined) {
  // 0.0.0 is a build from source, which is not on npm.
  const nsk = nskVersion && nskVersion !== '0.0.0' ? { '@diegomodesto/ns': `^${nskVersion}` } : {};
  return {
    name: name.toLowerCase().replace(/[^a-z0-9._-]+/g, '-'),
    private: true,
    scripts: {
      build: 'nsk build',
      watch: 'nsk watch',
      upload: 'nsk upload',
      deploy: 'nsk deploy',
      typecheck: 'tsc -p tsconfig.json',
    },
    devDependencies: { ...nsk, ...DEV_DEPENDENCIES },
  };
}

function tsconfig(outDir: string) {
  return {
    compilerOptions: {
      target: 'es2019',
      module: 'esnext',
      moduleResolution: 'bundler',
      strict: true,
      // tsc only type-checks; rollup.config.mjs emits the AMD files SuiteScript loads.
      noEmit: true,
      rootDir: SOURCE_DIR,
      outDir,
      lib: ['es2019', 'dom'],
      types: [],
      paths: {
        N: ['./node_modules/@hitc/netsuite-types/N'],
        'N/*': ['./node_modules/@hitc/netsuite-types/N/*'],
      },
    },
    include: [`${SOURCE_DIR}/**/*.ts`],
  };
}

function rollupConfig(outDir: string): string {
  return `// Generated by nsk init. TypeScript 7 cannot emit AMD, so tsc only type-checks and rollup emits one AMD
// file per module, keeping the folder structure. Keep sourceDir/outDir in sync with tsconfig.json rootDir/outDir.
import { readdirSync, readFileSync } from 'node:fs';
import { join } from 'node:path';
import esbuild from 'rollup-plugin-esbuild';

const sourceDir = '${SOURCE_DIR}';
const outDir = '${outDir}';

/** NetSuite modules have no default export: \`import record from 'N/record'\` would be undefined at runtime. */
function netsuiteImports() {
  const defaultImport = /^\\s*import\\s+(?!type\\b)[\\w$]+\\s*(?:,\\s*\\{[^}]*\\}\\s*)?from\\s*['"](N(?:\\/[\\w/]+)?)['"]/m;
  return {
    name: 'netsuite-imports',
    transform(code) {
      const match = code.match(defaultImport);
      if (match) this.error(\`use "import * as x from '\${match[1]}'" (NetSuite modules have no default export).\`);
      return null;
    },
  };
}

/** Keeps the JSDoc header (@NApiVersion, @NScriptType...) NetSuite reads; esbuild strips comments. */
function suiteScriptHeader() {
  const header = /^\\s*(\\/\\*\\*[\\s\\S]*?@NApiVersion[\\s\\S]*?\\*\\/)/;
  return {
    name: 'suitescript-header',
    renderChunk(code, chunk) {
      const match = chunk.facadeModuleId && readFileSync(chunk.facadeModuleId, 'utf8').match(header);
      return match ? \`\${match[1]}\\n\${code}\` : null;
    },
  };
}

export default {
  input: readdirSync(sourceDir, { recursive: true })
    .filter((file) => file.endsWith('.ts') && !file.endsWith('.d.ts'))
    .map((file) => join(sourceDir, file)),
  external: (id) => id === 'N' || id.startsWith('N/'),
  plugins: [netsuiteImports(), esbuild({ target: 'es2019' }), suiteScriptHeader()],
  output: {
    dir: outDir,
    format: 'amd',
    preserveModules: true,
    preserveModulesRoot: sourceDir,
    entryFileNames: '[name].js',
    interop: 'esModule',
    freeze: false,
  },
};
`;
}

function json(value: unknown): string {
  return JSON.stringify(value, null, 2) + '\n';
}
